#!/usr/bin/env bash
# Builds src/renderer/public/spatial-renderer.wasm and the off-thread
# spatial-hrtf-prep.wasm module from the pinned libspatialaudio/libmysofa
# submodules and the wrappers under native/spatial-wasm/.
#
# The .wasm artifact is committed to the repo (it is platform-independent);
# this script only needs to be re-run when the wrapper or the pinned
# either spatial submodule changes. Requires emscripten (emcc) on PATH
# (`brew install emscripten`) and the submodule checked out
# (`git submodule update --init third_party/libspatialaudio third_party/libmysofa`).

set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
LIB="$ROOT/third_party/libspatialaudio"
WRAPPER_DIR="$ROOT/native/spatial-wasm"
GEN_DIR="$WRAPPER_DIR/generated"
OUT="$ROOT/src/renderer/public/spatial-renderer.wasm"
PREP_OUT="$ROOT/src/renderer/public/spatial-hrtf-prep.wasm"
MYSOFA="$ROOT/third_party/libmysofa"

if ! command -v emcc >/dev/null 2>&1; then
  echo "error: emcc not found. Install emscripten (brew install emscripten)." >&2
  exit 1
fi
if [ ! -f "$LIB/include/Ambisonics.h" ]; then
  echo "error: libspatialaudio submodule missing. Run: git submodule update --init third_party/libspatialaudio" >&2
  exit 1
fi
if [ ! -f "$MYSOFA/src/hrtf/mysofa.h" ]; then
  echo "error: libmysofa submodule missing. Run: git submodule update --init third_party/libmysofa" >&2
  exit 1
fi

# Generate the config headers CMake would normally produce.
mkdir -p "$GEN_DIR"
cat > "$GEN_DIR/SpatialaudioConfig.h" <<'EOF'
/* Generated by scripts/build/build-spatial-wasm.sh — do not edit. */
#ifndef SPATIALAUDIO_CONFIG_H
#define SPATIALAUDIO_CONFIG_H

#define SPATIALAUDIO_MAJOR 0
#define SPATIALAUDIO_MINOR 4
#define SPATIALAUDIO_PATCH 1
#define SPATIALAUDIO_VERSION_STR "0.4.1"
#define SPATIALAUDIO_VERSION ((0 << 16) | (4 << 8) | 1)

#define SPATIALAUDIO_SUPPORTS_SOFA 1
#define SPATIALAUDIO_SUPPORTS_MIT_HRTF 1

#ifndef SPATIALAUDIO_STATIC
#define SPATIALAUDIO_STATIC
#endif

#endif /* SPATIALAUDIO_CONFIG_H */
EOF

cat > "$GEN_DIR/config.h" <<'EOF'
#ifndef _CONFIG_H
#define _CONFIG_H
#define CMAKE_INSTALL_PREFIX ""
#define CPACK_PACKAGE_VERSION_MAJOR 1
#define CPACK_PACKAGE_VERSION_MINOR 3
#define CPACK_PACKAGE_VERSION_PATCH 3
#endif
EOF

cat > "$GEN_DIR/mysofa_export.h" <<'EOF'
#ifndef MYSOFA_EXPORT
#define MYSOFA_EXPORT
#endif
EOF

CPP_SOURCES=(
  "$WRAPPER_DIR/spatial_wrapper.cpp"
  "$LIB/source/hrtf/mit_hrtf.cpp"
  "$LIB/source/AmbisonicCommons.cpp"
)
C_SOURCES=(
  "$LIB/source/mit_hrtf/mit_hrtf_lib.c"
  "$LIB/source/kiss_fft/kiss_fft.c"
  "$LIB/source/kiss_fft/kiss_fftr.c"
)

COMMON_FLAGS=(
  -O3
  -fno-exceptions
  -I "$GEN_DIR"
  -I "$LIB/include"
  -I "$LIB/source"
)

MYSOFA_FLAGS=(
  -O3
  -D__linux__
  -I "$GEN_DIR"
  -I "$MYSOFA/src"
  -I "$MYSOFA/src/hrtf"
  -I "$MYSOFA/src/hdf"
  -I "$MYSOFA/src/resampler"
  -sUSE_ZLIB=1
)

OBJ_DIR="$(mktemp -d)"
trap 'rm -rf "$OBJ_DIR"' EXIT
OBJECTS=()

echo "Building $OUT"
for src in "${CPP_SOURCES[@]}"; do
  obj="$OBJ_DIR/$(basename "${src%.*}").o"
  emcc -std=gnu++17 -fno-rtti "${COMMON_FLAGS[@]}" -c "$src" -o "$obj"
  OBJECTS+=("$obj")
done
for src in "${C_SOURCES[@]}"; do
  obj="$OBJ_DIR/$(basename "${src%.*}").o"
  emcc -std=gnu11 "${COMMON_FLAGS[@]}" -c "$src" -o "$obj"
  OBJECTS+=("$obj")
done

emcc \
  -O3 \
  -sSTANDALONE_WASM \
  --no-entry \
  -sEXPORTED_FUNCTIONS=_spatial_init,_spatial_init_prebaked,_spatial_speaker_filter_ptr,_spatial_commit_speaker_filter,_spatial_set_speaker,_spatial_clear_speaker,_spatial_input_ptr,_spatial_output_ptr,_spatial_process,_spatial_reset,_spatial_tail_taps \
  -sINITIAL_MEMORY=16MB \
  -sALLOW_MEMORY_GROWTH=0 \
  -o "$OUT" \
  "${OBJECTS[@]}"

ls -la "$OUT"
echo "Done."

MYSOFA_SOURCES=(
  "$MYSOFA/src/hrtf/reader.c"
  "$MYSOFA/src/hdf/superblock.c"
  "$MYSOFA/src/hdf/dataobject.c"
  "$MYSOFA/src/hdf/btree.c"
  "$MYSOFA/src/hdf/fractalhead.c"
  "$MYSOFA/src/hdf/gunzip.c"
  "$MYSOFA/src/hdf/gcol.c"
  "$MYSOFA/src/hrtf/check.c"
  "$MYSOFA/src/hrtf/spherical.c"
  "$MYSOFA/src/hrtf/lookup.c"
  "$MYSOFA/src/hrtf/tools.c"
  "$MYSOFA/src/hrtf/kdtree.c"
  "$MYSOFA/src/hrtf/neighbors.c"
  "$MYSOFA/src/hrtf/interpolate.c"
  "$MYSOFA/src/hrtf/resample.c"
  "$MYSOFA/src/hrtf/loudness.c"
  "$MYSOFA/src/hrtf/minphase.c"
  "$MYSOFA/src/hrtf/easy.c"
  "$MYSOFA/src/hrtf/cache.c"
  "$MYSOFA/src/resampler/speex_resampler.c"
)

PREP_OBJECTS=()
prep_cpp_sources=(
  "$WRAPPER_DIR/hrtf_prep_wrapper.cpp"
  "$LIB/source/hrtf/mit_hrtf.cpp"
  "$LIB/source/AmbisonicCommons.cpp"
)
prep_c_sources=(
  "$LIB/source/mit_hrtf/mit_hrtf_lib.c"
  "$LIB/source/kiss_fft/kiss_fft.c"
  "$LIB/source/kiss_fft/kiss_fftr.c"
  "${MYSOFA_SOURCES[@]}"
)

echo "Building $PREP_OUT"
prep_index=0
for src in "${prep_cpp_sources[@]}"; do
  obj="$OBJ_DIR/prep-$prep_index.o"
  prep_index=$((prep_index + 1))
  emcc -std=gnu++17 -fno-rtti -fno-exceptions "${COMMON_FLAGS[@]}" "${MYSOFA_FLAGS[@]}" -c "$src" -o "$obj"
  PREP_OBJECTS+=("$obj")
done
for src in "${prep_c_sources[@]}"; do
  obj="$OBJ_DIR/prep-$prep_index.o"
  prep_index=$((prep_index + 1))
  emcc -std=gnu11 "${COMMON_FLAGS[@]}" "${MYSOFA_FLAGS[@]}" -c "$src" -o "$obj"
  PREP_OBJECTS+=("$obj")
done

emcc \
  -O3 \
  -sSTANDALONE_WASM \
  --no-entry \
  -sUSE_ZLIB=1 \
  -sEXPORTED_FUNCTIONS=_hrtf_prep_init_builtin,_hrtf_prep_init_sofa,_hrtf_prep_bake,_hrtf_prep_filter_ptr,_hrtf_prep_last_error,_hrtf_prep_taps,_hrtf_prep_fft_size,_hrtf_prep_fft_bins,_hrtf_prep_filter_len,_hrtf_prep_reset,_malloc,_free \
  -sINITIAL_MEMORY=32MB \
  -sALLOW_MEMORY_GROWTH=1 \
  -sMAXIMUM_MEMORY=256MB \
  -o "$PREP_OUT" \
  "${PREP_OBJECTS[@]}"

ls -la "$PREP_OUT"
echo "Done."
