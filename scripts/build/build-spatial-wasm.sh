#!/usr/bin/env bash
# Builds src/renderer/public/spatial-renderer.wasm from the libspatialaudio
# submodule + native/spatial-wasm/spatial_wrapper.cpp.
#
# The .wasm artifact is committed to the repo (it is platform-independent);
# this script only needs to be re-run when the wrapper or the pinned
# libspatialaudio submodule changes. Requires emscripten (emcc) on PATH
# (`brew install emscripten`) and the submodule checked out
# (`git submodule update --init third_party/libspatialaudio`).

set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
LIB="$ROOT/third_party/libspatialaudio"
WRAPPER_DIR="$ROOT/native/spatial-wasm"
GEN_DIR="$WRAPPER_DIR/generated"
OUT="$ROOT/src/renderer/public/spatial-renderer.wasm"

if ! command -v emcc >/dev/null 2>&1; then
  echo "error: emcc not found. Install emscripten (brew install emscripten)." >&2
  exit 1
fi
if [ ! -f "$LIB/include/Ambisonics.h" ]; then
  echo "error: libspatialaudio submodule missing. Run: git submodule update --init third_party/libspatialaudio" >&2
  exit 1
fi

# Generate the config header CMake would normally produce (MIT HRTF on,
# SOFA off — SOFA/libmysofa is deferred; see plan).
mkdir -p "$GEN_DIR"
cat > "$GEN_DIR/SpatialaudioConfig.h" <<'EOF'
/* Generated by scripts/build/build-spatial-wasm.sh — do not edit. */
#ifndef SPATIALAUDIO_CONFIG_H
#define SPATIALAUDIO_CONFIG_H

#define SPATIALAUDIO_MAJOR 0
#define SPATIALAUDIO_MINOR 4
#define SPATIALAUDIO_PATCH 1
#define SPATIALAUDIO_VERSION_STR "0.4.1"
#define SPATIALAUDIO_VERSION ((0 << 16) | (4 << 8) | 1)

#define SPATIALAUDIO_SUPPORTS_SOFA 0
#define SPATIALAUDIO_SUPPORTS_MIT_HRTF 1

#ifndef SPATIALAUDIO_STATIC
#define SPATIALAUDIO_STATIC
#endif

#endif /* SPATIALAUDIO_CONFIG_H */
EOF

CPP_SOURCES=(
  "$WRAPPER_DIR/spatial_wrapper.cpp"
  "$LIB/source/hrtf/mit_hrtf.cpp"
  "$LIB/source/AmbisonicCommons.cpp"
)
C_SOURCES=(
  "$LIB/source/mit_hrtf/mit_hrtf_lib.c"
  "$LIB/source/kiss_fft/kiss_fft.c"
  "$LIB/source/kiss_fft/kiss_fftr.c"
)

COMMON_FLAGS=(
  -O3
  -fno-exceptions
  -I "$GEN_DIR"
  -I "$LIB/include"
  -I "$LIB/source"
)

OBJ_DIR="$(mktemp -d)"
trap 'rm -rf "$OBJ_DIR"' EXIT
OBJECTS=()

echo "Building $OUT"
for src in "${CPP_SOURCES[@]}"; do
  obj="$OBJ_DIR/$(basename "${src%.*}").o"
  emcc -std=gnu++17 -fno-rtti "${COMMON_FLAGS[@]}" -c "$src" -o "$obj"
  OBJECTS+=("$obj")
done
for src in "${C_SOURCES[@]}"; do
  obj="$OBJ_DIR/$(basename "${src%.*}").o"
  emcc -std=gnu11 "${COMMON_FLAGS[@]}" -c "$src" -o "$obj"
  OBJECTS+=("$obj")
done

emcc \
  -O3 \
  -sSTANDALONE_WASM \
  --no-entry \
  -sEXPORTED_FUNCTIONS=_spatial_init,_spatial_set_speaker,_spatial_clear_speaker,_spatial_input_ptr,_spatial_output_ptr,_spatial_process,_spatial_reset,_spatial_tail_taps \
  -sINITIAL_MEMORY=16MB \
  -sALLOW_MEMORY_GROWTH=0 \
  -o "$OUT" \
  "${OBJECTS[@]}"

ls -la "$OUT"
echo "Done."
